#!/usr/bin/env python3
"""
Validate a crew panel CSV before you spend GPU time on it.

Checks the things that otherwise surface as a confusing error twenty minutes into
a sweep — or worse, as a plausible-looking number that is actually an artefact.

    python scripts/validate_panel.py --dataset inspiration4
    python scripts/validate_panel.py --path data/raw/alsda_physiology/panel.csv
    python scripts/validate_panel.py --all

Exit codes: 0 = usable, 1 = errors found, 2 = file missing.

ERROR   blocks the run outright.
WARN    the run will proceed but a result may be invalid or uninterpretable.
INFO    context you should know before reading the numbers.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import datasets  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]
RESERVED = {
    "subject_id", "timepoint", "phase", "phase_source", "label", "label_acute",
    "split", "sample_id", "accession",
}
MIN_SUBJECTS_FOR_SPLIT = 6      # 60/15/25 subject-wise needs at least this many
MIN_SUBJECTS_COMFORTABLE = 15


class Report:
    """Accumulates findings and prints them grouped by severity."""

    def __init__(self, label: str) -> None:
        self.label = label
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.info: list[str] = []

    def error(self, message: str) -> None:
        self.errors.append(message)

    def warn(self, message: str) -> None:
        self.warnings.append(message)

    def note(self, message: str) -> None:
        self.info.append(message)

    def render(self) -> bool:
        print(f"\n{'=' * 72}\n  {self.label}\n{'=' * 72}")
        for message in self.info:
            print(f"  INFO   {message}")
        for message in self.warnings:
            print(f"  WARN   {message}")
        for message in self.errors:
            print(f"  ERROR  {message}")

        if self.errors:
            print(f"\n  -> NOT USABLE: {len(self.errors)} error(s) must be fixed.")
            return False
        if self.warnings:
            print(f"\n  -> USABLE with {len(self.warnings)} caveat(s). Read them before reporting.")
            return True
        print("\n  -> Looks good.")
        return True


#: Written beside generated panels by scripts/make_example_panel.py.
SYNTHETIC_MARKER = "SYNTHETIC.txt"


def validate(path: Path, label: str | None = None) -> Report:
    report = Report(label or str(path))

    marker = path.parent / SYNTHETIC_MARKER
    if marker.exists():
        report.error(
            f"SIMULATED DATA: {marker.parent.name}/{SYNTHETIC_MARKER} marks this panel as "
            f"generated by scripts/make_example_panel.py, not measured. No number "
            f"computed from it is reportable. Replace panel.csv with a real export "
            f"and delete the marker."
        )
        return report

    try:
        frame = pd.read_csv(path, sep="\t" if path.suffix == ".tsv" else ",")
    except Exception as exc:  # noqa: BLE001
        report.error(f"cannot parse the file: {type(exc).__name__}: {exc}")
        return report

    frame.columns = [str(c).strip() for c in frame.columns]
    report.note(f"{len(frame)} rows x {len(frame.columns)} columns")

    # -- required columns ------------------------------------------------
    for column in ("subject_id", "timepoint"):
        if column not in frame.columns:
            report.error(f"missing required column '{column}'")
    if report.errors:
        return report

    # -- cohort size -----------------------------------------------------
    n_subjects = frame["subject_id"].nunique()
    report.note(f"{n_subjects} distinct subject(s), {frame['timepoint'].nunique()} timepoint(s)")

    if n_subjects < 2:
        report.error(f"only {n_subjects} subject — no split is possible")
    elif n_subjects < MIN_SUBJECTS_FOR_SPLIT:
        report.warn(
            f"only {n_subjects} subjects: a 60/15/25 subject-wise split leaves ~"
            f"{max(1, round(0.25 * n_subjects))} in test. Use leave-one-subject-out "
            f"cross-validation and report per-subject results, not a pooled score."
        )
    elif n_subjects < MIN_SUBJECTS_COMFORTABLE:
        report.warn(
            f"{n_subjects} subjects is small. Report per-subject variance alongside "
            f"the pooled metric, and expect deep models to overfit."
        )

    rows_per_subject = frame.groupby("subject_id").size()
    if rows_per_subject.min() < 2:
        thin = rows_per_subject[rows_per_subject < 2].index.tolist()
        report.warn(f"subject(s) with a single row: {thin[:5]}"
                    f"{' ...' if len(thin) > 5 else ''}")

    # -- phase / baseline ------------------------------------------------
    if "phase" in frame.columns:
        phases = frame["phase"].astype(str).str.lower()
    else:
        report.note("no 'phase' column — inferring from 'timepoint' prefixes")
        phases = frame["timepoint"].astype(str).map(_infer_phase)

    counts = phases.value_counts().to_dict()
    report.note("phase distribution: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))

    if counts.get("unknown", 0):
        unrecognised = sorted(set(frame.loc[phases == "unknown", "timepoint"].astype(str)))[:6]
        report.warn(
            f"{counts['unknown']} row(s) have an unrecognised timepoint format: "
            f"{unrecognised}. Expected L-<n> / FD<n> / R+<n> / pre* / in* / post*. "
            f"These get no phase and will not contribute to a baseline."
        )

    preflight_subjects = set(frame.loc[phases == "preflight", "subject_id"].unique())
    without_baseline = sorted(set(frame["subject_id"].unique()) - preflight_subjects)
    if not preflight_subjects:
        report.error(
            "no preflight rows at all — the own-baseline deviation channel cannot be "
            "computed, which is the core of the representation. Mark preflight "
            "timepoints (L-<n>) or add a 'phase' column."
        )
    elif without_baseline:
        report.warn(
            f"{len(without_baseline)} subject(s) have no preflight sample "
            f"({without_baseline[:5]}{' ...' if len(without_baseline) > 5 else ''}); "
            f"they fall back to their own overall mean, which leaks postflight "
            f"information into the baseline."
        )

    # -- features --------------------------------------------------------
    numeric = [c for c in frame.columns
               if c not in RESERVED and pd.api.types.is_numeric_dtype(frame[c])]
    non_numeric = [c for c in frame.columns if c not in RESERVED and c not in numeric]

    if not numeric:
        report.error("no numeric feature columns found — nothing to model")
        return report
    report.note(f"{len(numeric)} numeric feature column(s)")

    if non_numeric:
        report.warn(
            f"{len(non_numeric)} non-numeric column(s) will be silently ignored: "
            f"{non_numeric[:6]}{' ...' if len(non_numeric) > 6 else ''}"
        )

    values = frame[numeric]
    all_nan = [c for c in numeric if values[c].isna().all()]
    if all_nan:
        report.error(f"column(s) entirely NaN: {all_nan[:6]}")

    mostly_nan = [c for c in numeric if 0.5 < values[c].isna().mean() < 1.0]
    if mostly_nan:
        report.warn(f"column(s) >50% NaN, median-imputed: {mostly_nan[:6]}")

    constant = [c for c in numeric if values[c].nunique(dropna=True) <= 1 and c not in all_nan]
    if constant:
        report.warn(f"constant column(s), zero information: {constant[:6]}")

    if len(numeric) > 3 * len(frame):
        report.warn(
            f"{len(numeric)} features vs {len(frame)} samples — severely "
            f"under-determined. Reduce dimensionality (pathway/panel aggregation) "
            f"before modelling."
        )

    # -- labels ----------------------------------------------------------
    if "label" not in frame.columns:
        report.warn(
            "no 'label' column. The loader will derive one by thresholding "
            "baseline deviation, which is CIRCULAR — the label becomes a function "
            "of the features the model receives. The run will be marked "
            "non-reportable. Supply a clinical label before reporting."
        )
    else:
        labels = frame["label"]
        unique = sorted(labels.dropna().unique().tolist())
        report.note(f"label values: {unique}")

        if labels.isna().any():
            report.error(f"{int(labels.isna().sum())} row(s) have a missing label")
        if len(unique) < 2:
            report.error(f"label has only one class ({unique}) — nothing to discriminate")
        elif not set(unique) <= {0, 1}:
            report.warn(f"labels are not 0/1: {unique}. The pipeline treats 1 as "
                        f"'deteriorated' and everything else as nominal.")
        else:
            rate = float((labels == 1).mean())
            report.note(f"positive (deteriorated) rate: {rate:.1%}")
            if rate < 0.05 or rate > 0.95:
                report.warn(
                    f"severe class imbalance ({rate:.1%} positive). Balanced accuracy "
                    f"and AUPRC will be noisy; consider pooling cohorts."
                )

        # Label constant within a subject means subject identity predicts the label.
        per_subject = frame.groupby("subject_id")["label"].nunique()
        if (per_subject <= 1).all() and n_subjects > 2:
            report.warn(
                "every subject has a single label value — with a subject-wise split "
                "the model can score well by recognising individuals rather than "
                "deterioration. Prefer within-subject labels (a crew member is "
                "nominal at some timepoints and deteriorated at others)."
            )

        _check_shortcuts(frame, numeric, report)

    # -- split -----------------------------------------------------------
    if "split" in frame.columns:
        present = sorted(frame["split"].astype(str).unique())
        report.note(f"explicit split column: {present}")
        missing = {"train", "test"} - set(present)
        if missing:
            report.error(f"split column is missing {sorted(missing)}")
        overlap = (frame.groupby("subject_id")["split"].nunique() > 1)
        if overlap.any():
            report.error(
                f"{int(overlap.sum())} subject(s) appear in more than one split — "
                f"this leaks crew members between train and test."
            )
    else:
        report.note("no 'split' column — a deterministic subject-wise split will be derived")

    return report


def _auroc(y: "pd.Series", score: "pd.Series") -> float:
    """Rank AUROC, ties averaged. Local so this module keeps no sklearn dep."""
    y = np.asarray(y, dtype=int)
    score = np.asarray(score, dtype=float)
    n_pos, n_neg = int((y == 1).sum()), int((y == 0).sum())
    if n_pos == 0 or n_neg == 0:
        return float("nan")
    ranks = pd.Series(score).rank(method="average").to_numpy()
    return float((ranks[y == 1].sum() - n_pos * (n_pos + 1) / 2) / (n_pos * n_neg))


def _check_shortcuts(frame, numeric: list[str], report) -> None:
    """Look for things that predict the label without being physiology.

    Both of these were found by hand in real panels here and neither shows up
    in any per-column check:

    * **Missingness as a signal.** Inspiration4 has one crew member whose entire
      406-analyte immune panel is absent at one preflight draw. Median
      imputation then makes that row distinctive, and "how much of this row was
      imputed" carries label information on its own.
    * **A covariate that tracks the label.** OSD-370's recovery arm was assayed
      only under the baseline treatment condition, so "is this sample
      insulin-stimulated" partly predicts the bed-rest label.
    """
    labels = frame["label"]
    if labels.isna().any() or labels.nunique() < 2:
        return

    if numeric:
        missing_count = frame[numeric].isna().sum(axis=1)
        if missing_count.max() > 0:
            auroc = _auroc(labels, missing_count)
            if auroc == auroc and abs(auroc - 0.5) > 0.1:
                report.warn(
                    f"missingness predicts the label (AUROC {auroc:.3f} from the "
                    f"per-row NaN count alone). Imputed values become a shortcut. "
                    f"Check which rows are incomplete and consider dropping "
                    f"features that are not measured at every timepoint."
                )

    for column in frame.columns:
        if column in RESERVED or column in numeric:
            continue
        values = frame[column]
        if values.nunique(dropna=True) < 2 or values.nunique(dropna=True) > 10:
            continue
        worst, level = 0.5, None
        for value in values.dropna().unique():
            auroc = _auroc(labels, (values == value).astype(int))
            if auroc == auroc and abs(auroc - 0.5) > abs(worst - 0.5):
                worst, level = auroc, value
        if abs(worst - 0.5) > 0.1:
            report.warn(
                f"covariate '{column}' tracks the label (AUROC {worst:.3f} for "
                f"'{level}' alone). A model can score by reading the study design "
                f"rather than physiology — check the arms are balanced."
            )


def _infer_phase(timepoint: str) -> str:
    label = str(timepoint).strip().upper()
    if label.startswith("L-") or label.startswith("PRE"):
        return "preflight"
    if label.startswith("FD") or label.startswith("IN") or label.startswith("MD"):
        return "inflight"
    if label.startswith("R+") or label.startswith("POST"):
        return "postflight"
    return "unknown"


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--dataset", help="Registry key; resolves data/raw/<key>/*.csv")
    parser.add_argument("--path", help="Explicit path to a CSV/TSV")
    parser.add_argument("--all", action="store_true",
                        help="Validate every registered panel-backed dataset")
    parser.add_argument("--data-root", default=None, help="Defaults to <repo>/data/raw")
    args = parser.parse_args()

    data_root = Path(args.data_root) if args.data_root else REPO_ROOT / "data" / "raw"

    targets: list[tuple[Path, str]] = []
    if args.path:
        targets.append((Path(args.path), args.path))
    if args.dataset:
        targets += _resolve(args.dataset, data_root)
    if args.all:
        for key in datasets.REAL_DATASET_KEYS:
            targets += _resolve(key, data_root)
    if not targets:
        parser.print_help()
        return 0

    ok = True
    missing = 0
    for path, label in targets:
        if not path.exists():
            print(f"\n{'=' * 72}\n  {label}\n{'=' * 72}")
            print(f"  MISSING  no file at {path}")
            print("           see docs/DATASETS.md for how to export a panel")
            missing += 1
            continue
        ok = validate(path, label).render() and ok

    print()
    if missing:
        print(f"{missing} dataset(s) have no file yet.")
    return 1 if not ok else (2 if missing and len(targets) == missing else 0)


def _resolve(key: str, data_root: Path) -> list[tuple[Path, str]]:
    if key not in datasets.REAL_DATASET_KEYS:
        print(f"unknown dataset key '{key}'. Known: {sorted(datasets.REAL_DATASET_KEYS)}")
        return []
    root = data_root / key
    if root.is_dir():
        found = sorted(list(root.glob("*.csv")) + list(root.glob("*.tsv")))
        if found:
            return [(found[0], f"{key}  ({found[0]})")]
    return [(root / "panel.csv", f"{key}  ({root / 'panel.csv'})")]


if __name__ == "__main__":
    raise SystemExit(main())
