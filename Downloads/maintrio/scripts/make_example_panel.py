#!/usr/bin/env python3
"""
Generate an example longitudinal crew panel in the exact shape the
``longitudinal_panel`` loader expects.

This is a **format template, not data**. Run it once so you can see the column
layout and get ``run.py`` executing end to end, then replace the generated
CSV with a real export from OSDR / GeneLab / ALSDA / Inspiration4.

    python scripts/make_example_panel.py --dataset inspiration4
    python scripts/make_example_panel.py --dataset alsda_physiology --n-subjects 18

Required columns
----------------
    subject_id   crew member identifier
    timepoint    L-92, L-44, L-3, FD1, FD2, R+1, R+45, R+82, R+194, ...
    phase        preflight | inflight | postflight   (inferred if omitted)
    <measures>   any number of numeric columns
    label        optional; derived from own-baseline deviation when absent
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]

#: Dropped beside every generated panel. The printed warning only reaches
#: whoever runs the generator; a later session opening data/raw/<key>/panel.csv
#: has no way to tell simulated numbers from a real OSDR export unless the
#: fabrication is recorded next to the file itself.
MARKER = "SYNTHETIC.txt"


def write_marker(destination: Path, dataset: str, seed: int) -> Path:
    path = destination / MARKER
    path.write_text(
        "SIMULATED DATA - NOT A REAL MEASUREMENT\n"
        "=======================================\n\n"
        f"data/raw/{dataset}/panel.csv was generated by\n"
        f"scripts/make_example_panel.py (seed={seed}).\n\n"
        "Every value is drawn from a random number generator. It exists to show\n"
        "the column layout and to let run.py execute end to end. No number\n"
        "computed from it means anything, and none of it may appear in a table,\n"
        "a figure or a paper.\n\n"
        "Delete this file only when panel.csv has been replaced by a real export.\n"
        "scripts/validate_panel.py treats its presence as a hard error.\n",
        encoding="utf-8",
    )
    return path

TIMEPOINTS = [
    ("L-92", "preflight"), ("L-44", "preflight"), ("L-3", "preflight"),
    ("FD1", "inflight"), ("FD2", "inflight"), ("FD3", "inflight"),
    ("R+1", "postflight"), ("R+45", "postflight"), ("R+82", "postflight"),
    ("R+194", "postflight"),
]

# Measures chosen to mirror what OSDR/ALSDA human studies actually report.
MEASURES = {
    "heart_rate_bpm": (68.0, 6.0),
    "hrv_rmssd_ms": (45.0, 9.0),
    "systolic_bp_mmhg": (118.0, 8.0),
    "plasma_volume_pct": (100.0, 4.0),
    "bone_density_tscore": (0.2, 0.5),
    "grip_strength_kg": (44.0, 7.0),
    "postural_sway_area_mm2": (210.0, 45.0),
    "gait_speed_m_s": (1.35, 0.12),
    "sleep_efficiency_pct": (88.0, 5.0),
    "actigraphy_counts_k": (310.0, 55.0),
    "crp_mg_l": (1.4, 0.7),
    "cortisol_ug_dl": (12.0, 3.0),
}

# Fractional shift applied at peak inflight/early-postflight deconditioning.
FLIGHT_EFFECT = {
    "hrv_rmssd_ms": -0.22, "plasma_volume_pct": -0.11, "bone_density_tscore": -0.30,
    "grip_strength_kg": -0.12, "postural_sway_area_mm2": +0.35, "gait_speed_m_s": -0.10,
    "sleep_efficiency_pct": -0.09, "crp_mg_l": +0.40, "cortisol_ug_dl": +0.25,
}


def build_panel(n_subjects: int, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = []
    for subject in range(n_subjects):
        offsets = {m: rng.normal(0, sd * 0.6) for m, (_, sd) in MEASURES.items()}
        susceptibility = rng.uniform(0.5, 1.5)  # crew members decondition differently
        for timepoint, phase in TIMEPOINTS:
            weight = {"preflight": 0.0, "inflight": 1.0}.get(phase)
            if weight is None:  # postflight recovery decays with days since return
                days = float(timepoint.split("+")[1])
                weight = float(np.exp(-days / 60.0))
            row = {
                "subject_id": f"CREW-{subject + 1:02d}",
                "timepoint": timepoint,
                "phase": phase,
            }
            for measure, (mean, sd) in MEASURES.items():
                effect = FLIGHT_EFFECT.get(measure, 0.0) * weight * susceptibility
                row[measure] = float(mean * (1 + effect) + offsets[measure] + rng.normal(0, sd * 0.35))
            rows.append(row)
    return pd.DataFrame(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", default="inspiration4",
                        help="Registry key; also the folder under data/raw/.")
    parser.add_argument("--n-subjects", type=int, default=4,
                        help="Inspiration4 flew 4; analogue studies are usually larger.")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--data-root", default=None, help="Defaults to <repo>/data")
    args = parser.parse_args()

    data_root = Path(args.data_root) if args.data_root else REPO_ROOT / "data"
    destination = data_root / "raw" / args.dataset
    destination.mkdir(parents=True, exist_ok=True)

    panel = build_panel(args.n_subjects, args.seed)
    path = destination / "panel.csv"
    panel.to_csv(path, index=False)
    write_marker(destination, args.dataset, args.seed)

    print(f"wrote {path}")
    print(f"  {len(panel)} rows | {args.n_subjects} crew members | "
          f"{len(TIMEPOINTS)} timepoints | {len(MEASURES)} measures")
    print("\nEXAMPLE DATA ONLY — replace with a real OSDR/ALSDA/I4 export before reporting.")
    print(f"Dropped a {MARKER} marker beside it; validate_panel.py errors out")
    print("on any panel carrying one, so this can never be reported by accident.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
